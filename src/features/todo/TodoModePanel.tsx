  const stopRecurringTemplate = async (viewModel: TodoViewModel) => {
    const { item } = viewModel.internalRef

    if (!item.templateId || !viewModel.canStopRepeating) {
      return
    }

    const nextArchivedState = !viewModel.isRecurringStopped
    const confirmed = window.confirm(
      nextArchivedState
        ? `确认停止「${item.title}」的重复吗？已生成的历史实例会保留，但未来不再自动出现。`
        : `确认恢复「${item.title}」的重复吗？未来命中日会重新自动出现。`,
    )

    if (!confirmed) {
      return
    }

    if (!nextArchivedState) {
      await appDataRepository.taskTemplates.update({
        id: item.templateId,
        isArchived: false,
      })

      await reloadItems()
      return
    }

    const [recurringInstances, dayPlanItems] = await Promise.all([
      appDataRepository.recurringTaskInstances.list(),
      appDataRepository.dayPlanItems.list(),
    ])

    const removedRecurringInstanceIds = new Set(
      recurringInstances
        .filter(
          (instance) =>
            instance.templateId === item.templateId &&
            (instance.targetDate ?? instance.dateKey) > selectedDateKey,
        )
        .map((instance) => instance.id),
    )

    const recurringInstancesToDelete = recurringInstances.filter((instance) =>
      removedRecurringInstanceIds.has(instance.id),
    )
    const dayPlanItemsToDelete = dayPlanItems.filter((dayPlanItem) => {
      if (dayPlanItem.templateId !== item.templateId) {
        return false
      }

      if (getOccurrenceTargetDateKey(dayPlanItem) <= selectedDateKey) {
        return false
      }

      if (!dayPlanItem.recurringInstanceId) {
        return true
      }

      return removedRecurringInstanceIds.has(dayPlanItem.recurringInstanceId)
    })

    await appDataRepository.taskTemplates.update({
      id: item.templateId,
      isArchived: true,
      updatedAt: new Date().toISOString(),
    })

    await Promise.all([
      ...recurringInstancesToDelete.map((instance) =>
        appDataRepository.recurringTaskInstances.delete(instance.id),
      ),
      ...dayPlanItemsToDelete.map((dayPlanItem) =>
        appDataRepository.dayPlanItems.delete(dayPlanItem.id),
      ),
    ])

    await reloadItems()
  }

  const persistIncompleteOrder = async (
    reorderedDayItems: TodoViewModel[],
    reorderedNightItems: TodoViewModel[],
    activeItemId: string,
  ) => {
    setSortingItemId(activeItemId)

    try {
      const reorderedItemsById = new Map<string, ReorderedItemState>([
        ...reorderedDayItems.map<[string, ReorderedItemState]>((viewModel, index) => {
          const previousItem = viewModel.internalRef.item

          return [
            viewModel.id,
            {
              sortOrder: index + 1,
              timeBlock: 'day' as TimeBlock,
              timeBlockSource:
                previousItem.timeBlock === 'day' ? previousItem.timeBlockSource : 'default_day',
            },
          ]
        }),
        ...reorderedNightItems.map<[string, ReorderedItemState]>((viewModel, index) => {
          const previousItem = viewModel.internalRef.item

          return [
            viewModel.id,
            {
              sortOrder: reorderedDayItems.length + index + 1,
              timeBlock: 'night' as TimeBlock,
              timeBlockSource:
                previousItem.timeBlock === 'night' ? previousItem.timeBlockSource : 'manual_night',
            },
          ]
        }),
      ])

      await Promise.all(
        Array.from(reorderedItemsById.entries()).map(([id, nextState]) =>
          appDataRepository.dayPlanItems.update({
            id,
            sortOrder: nextState.sortOrder,
            timeBlock: nextState.timeBlock,
            timeBlockSource: nextState.timeBlockSource,
          }),
        ),
      )

      await reloadItems()
    } finally {
      setSortingItemId((current) => (current === activeItemId ? null : current))
    }
  }

  const handleSortEnd = (event: DragEndEvent) => {
    const { active, over } = event

    if (!over || active.id === over.id || active.id === DAY_NIGHT_DIVIDER_ID) {
      return
    }

    const activeIndex = sortableItemIds.indexOf(String(active.id))
    const overIndex = sortableItemIds.indexOf(String(over.id))

    if (activeIndex === -1 || overIndex === -1) {
      return
    }

    const reorderedIds = arrayMove(sortableItemIds, activeIndex, overIndex)
    const dividerIndex = reorderedIds.indexOf(DAY_NIGHT_DIVIDER_ID)
    const itemsById = new Map(incompleteItems.map((item) => [item.id, item]))
    const reorderedDayItems = reorderedIds
      .slice(0, dividerIndex)
      .map((id) => itemsById.get(id))
      .filter((item): item is TodoViewModel => Boolean(item))
    const reorderedNightItems = reorderedIds
      .slice(dividerIndex + 1)
      .map((id) => itemsById.get(id))
      .filter((item): item is TodoViewModel => Boolean(item))

    void persistIncompleteOrder(reorderedDayItems, reorderedNightItems, String(active.id))
  }


async function refreshExistingLogbookForDate(dateKey: string) {
  await appDataRepository.update((current) => refreshExistingLogbookEntryForDate(current, dateKey))
}

async function syncSegmentedRollbackProgressLog(item: DayPlanItem, dateKey: string, nextProgressPercent: number) {
  await appDataRepository.update((current) => {
    const existingLog = current.segmentedProgressLogs.find(
      (log) => log.date === dateKey && log.itemId === item.id,
    )

    if (!existingLog) {
      return current
    }

    return {
      ...current,
      segmentedProgressLogs: current.segmentedProgressLogs.map((log) =>
        log.date === dateKey && log.itemId === item.id
          ? {
              ...log,
              titleSnapshot: item.title,
              isNecessary: item.isNecessary,
              toProgress: nextProgressPercent,
            }
          : log,
      ),
    }
  })
}

function RecommendationInlineCard({
  activityTypes,
  sceneTags,
  panelState,
  onActivityTypeChange,
  onSceneTagToggle,
  onConfirm,
}: {
  activityTypes: ActivityType[]
  sceneTags: SceneTag[]
  panelState: RecommendationPanelState
  onActivityTypeChange: (activityTypeId: string) => void
  onSceneTagToggle: (sceneTagId: string) => void
  onConfirm: (template: TaskTemplate) => void
}) {
  const visibleCandidates = panelState.candidates
  const getInterestActionOpacity = (level: number, maxLevel = 3) => {
    if (maxLevel <= 1) {
      return 1
    }

    const normalized = Math.max(0, Math.min(1, (level - 1) / (maxLevel - 1)))

    return 0.45 + normalized * 0.55
  }

  return (
    <div className="recommendation-card">
      <div className="recommendation-card__filter-group">
        <p className="recommendation-card__filter-label">按清单筛选</p>
      <div className="recommendation-card__activity-types" aria-label="种草清单">
        {activityTypes.map((activityType) => (
          <button
            key={activityType.id}
            className={
              panelState.activityTypeId === activityType.id
                ? 'tag-chip tag-chip--selected tag-chip--button'
                : 'tag-chip tag-chip--button'
            }
            type="button"
            onClick={() => {
              onActivityTypeChange(activityType.id)
            }}
          >
            <span className="tag-chip__label">{activityType.name}</span>
          </button>
        ))}
      </div>
      </div>

      <div className="recommendation-card__filter-group">
        <p className="recommendation-card__filter-label">按场景筛选</p>
      <div className="recommendation-card__activity-types" aria-label="场景标签">
        {sceneTags.map((sceneTag) => (
          <button
            key={sceneTag.id}
            className={
              panelState.sceneTagIds.includes(sceneTag.id)
                ? 'tag-chip tag-chip--selected tag-chip--button'
                : 'tag-chip tag-chip--button'
            }
            type="button"
            onClick={() => {
              onSceneTagToggle(sceneTag.id)
            }}
          >
            <span className="tag-chip__label">{sceneTag.name}</span>
          </button>
        ))}
      </div>
      </div>

      {panelState.isLoading ? (
        <p className="form-message">正在加载候选...</p>
      ) : panelState.errorMessage ? (
        <p className="form-message form-message--danger">{panelState.errorMessage}</p>
      ) : (
        <div className="recommendation-card__body">
          {visibleCandidates.length === 0 ? (
            <div className="empty-state-card">
              <p>没有可选候选</p>
            </div>
          ) : (
            <div className="candidate-list candidate-list--scrollable">
              {visibleCandidates.map((candidate) => {
                const actionOpacity = getInterestActionOpacity(candidate.interestLevel)

                return (
                  <article className="candidate-item" key={candidate.id}>
                    <div className="candidate-item__main">
                      <h6>{candidate.title}</h6>
                    </div>
                    <button
                      className="candidate-item__add-button"
                      type="button"
                      onClick={() => {
                        onConfirm(candidate)
                      }}
                      aria-label={`添加 ${candidate.title}`}
                      title="添加"
                      style={{ opacity: actionOpacity }}
                    >
                      <PlusIcon className="candidate-item__add-icon" />
                    </button>
                  </article>
                )
              })}
            </div>
          )}
        </div>
      )}
    </div>
  )
}


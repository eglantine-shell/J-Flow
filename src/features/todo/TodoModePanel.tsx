  const updateSegmentedProgress = async (
    viewModel: TodoViewModel,
    nextProgressPercent: number,
  ) => {
    const { item } = viewModel.internalRef

    if (!viewModel.isSegmented) {
      return
    }

    const normalizedProgressPercent = Math.max(
      0,
      Math.min(100, Number.isNaN(nextProgressPercent) ? item.progressPercent : nextProgressPercent),
    )
    const nextProgressState =
      normalizedProgressPercent === 0
        ? 'not_started'
        : normalizedProgressPercent === 100
          ? 'completed'
          : 'in_progress'
    const nowIso = await getRecordedCompletedAtIso()
    const isCompleted = normalizedProgressPercent === 100

    await appDataRepository.dayPlanItems.update({
      id: item.id,
      progressPercent: normalizedProgressPercent,
      progressState: nextProgressState,
      status: isCompleted ? 'completed' : 'pending',
      completedAt: isCompleted ? nowIso : undefined,
      consumesDateTrigger:
        isCompleted && Boolean(item.templateId && item.targetDate)
          ? true
          : false,
    })

    if (item.recurringInstanceId) {
      await appDataRepository.recurringTaskInstances.update({
        id: item.recurringInstanceId,
        progressPercent: normalizedProgressPercent,
        progressState: nextProgressState,
        status: isCompleted ? 'completed' : 'pending',
        completedAt: isCompleted ? nowIso : undefined,
      })
    }

    if (normalizedProgressPercent !== item.progressPercent) {
      const progressLogDateKey = toDateString(new Date())

      await appDataRepository.update((current) => {
        const existingLog = current.segmentedProgressLogs.find(
          (log) => log.date === progressLogDateKey && log.itemId === item.id,
        )

        const shouldCreateLog =
          normalizedProgressPercent > item.progressPercent || Boolean(existingLog)

        if (!shouldCreateLog) {
          return current
        }

        const nextLog = existingLog
          ? {
              ...existingLog,
              titleSnapshot: item.title,
              isNecessary: item.isNecessary,
              // Keep the first progress point of the day, but always reflect
              // the most recent progress value as the day's end snapshot.
              toProgress: normalizedProgressPercent,
            }
          : {
              date: progressLogDateKey,
              itemId: item.id,
              titleSnapshot: item.title,
              isNecessary: item.isNecessary,
              fromProgress: item.progressPercent,
              toProgress: normalizedProgressPercent,
            }

        return {
          ...current,
          segmentedProgressLogs: existingLog
            ? current.segmentedProgressLogs.map((log) =>
                log.date === progressLogDateKey && log.itemId === item.id ? nextLog : log,
              )
            : [...current.segmentedProgressLogs, nextLog],
        }
      })
    }

    await reloadItems()
  }


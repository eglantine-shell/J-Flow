const pad = (value: number) => String(value).padStart(2, '0')

const toDateString = (date: Date) =>
  `${date.getFullYear()}-${pad(date.getMonth() + 1)}-${pad(date.getDate())}`

const toDateTimeLocalValue = (iso?: string) => {
  if (!iso) {
    return ''
  }

  const date = new Date(iso)

  if (Number.isNaN(date.getTime())) {
    return ''
  }

  return `${date.getFullYear()}-${pad(date.getMonth() + 1)}-${pad(date.getDate())}T${pad(date.getHours())}:${pad(date.getMinutes())}`
}

const toDateValue = (value?: string) => {
  if (!value) {
    return ''
  }

  const [year, month, day] = value.split('-')

  if (!year || !month || !day) {
    return ''
  }

  return `${year}-${month}-${day}`
}

const parseDateInputValue = (value: string) => {
  const [year, month, day] = value.split('-').map(Number)

  if (!year || !month || !day) {
    return null
  }

  return new Date(year, month - 1, day)
}

const parseDeadlineWithinDaysInput = (value: string) => {
  if (!/^\d+$/.test(value.trim())) {
    return null
  }

  const parsed = Number(value)

  if (!Number.isInteger(parsed) || parsed < 1 || parsed > 100) {
    return null
  }

  return parsed
}

const formatComposerDateLabel = (dateKey: string, selectedDateKey: string) => {
  if (dateKey === selectedDateKey) {
    return '当天'
  }

  const [, month, day] = dateKey.split('-')

  if (!month || !day) {
    return '改期'
  }

  return `${Number(month)}/${Number(day)}`
}

const toCompletedAtIso = (value: string) => {
  if (!value) {
    return null
  }

  const date = new Date(value)

  if (Number.isNaN(date.getTime())) {
    return null
  }

  return date.toISOString()
}

const getCompletedDisplayDateKey = (completedAt?: string) => {
  if (!completedAt) {
    return null
  }

  const date = new Date(completedAt)

  if (Number.isNaN(date.getTime())) {
    return null
  }

  return toDateString(date)
}

const getDisplayDateKeyForItem = (item: Pick<DayPlanItem, 'date' | 'status' | 'completedAt'>) => {
  if (item.status === 'completed') {
    return getCompletedDisplayDateKey(item.completedAt) ?? item.date
  }

  return item.date
}

const isVisibleOnSelectedDate = (
  item: Pick<DayPlanItem, 'date' | 'status' | 'completedAt'>,
  selectedDateKey: string,
) => getDisplayDateKeyForItem(item) === selectedDateKey

const getOccurrenceTargetDateKey = (
  item: Pick<DayPlanItem, 'date' | 'targetDate'>,
) => item.targetDate ?? item.date

const getCompletedSortTimestamp = (item: Pick<DayPlanItem, 'completedAt'>) => {
  if (!item.completedAt) {
    return Number.POSITIVE_INFINITY
  }

  const timestamp = new Date(item.completedAt).getTime()

  return Number.isNaN(timestamp) ? Number.POSITIVE_INFINITY : timestamp
}

const formatCompletedTimeEditorLabel = (completedAt?: string) => {
  if (!completedAt) {
    return '完成时间待补'
  }

  const date = new Date(completedAt)

  if (Number.isNaN(date.getTime())) {
    return '完成时间待补'
  }

  return `完成于 ${pad(date.getMonth() + 1)}/${pad(date.getDate())} ${pad(date.getHours())}:${pad(date.getMinutes())}`
}

const DAY_SCENE_NAMES = new Set(['上午', '下午', '白天'])
const NIGHT_SCENE_NAMES = new Set(['晚上', '夜间'])


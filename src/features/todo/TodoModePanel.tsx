function sortTodoItems(items: DayPlanItem[]) {
  return [...items].sort((left, right) => {
    const leftCompleted = left.status === 'completed'
    const rightCompleted = right.status === 'completed'

    if (leftCompleted !== rightCompleted) {
      return leftCompleted ? 1 : -1
    }

    if (leftCompleted && rightCompleted) {
      const completedAtDiff = getCompletedSortTimestamp(left) - getCompletedSortTimestamp(right)

      if (completedAtDiff !== 0) {
        return completedAtDiff
      }

      return left.createdAt.localeCompare(right.createdAt)
    }

    if (left.timeBlock !== right.timeBlock) {
      return left.timeBlock === 'day' ? -1 : 1
    }

    if (left.sortOrder !== right.sortOrder) {
      return left.sortOrder - right.sortOrder
    }

    return left.createdAt.localeCompare(right.createdAt)
  })
}

async function syncSelectedDateData(selectedDate: Date) {
  await syncAutoGeneratedDayPlanForDate(selectedDate)

  if (toDateString(selectedDate) === toDateString(new Date())) {
    await syncTodoCarryoversForDate(selectedDate)
  }
}

async function syncSelectedDateDataWithLogbook(selectedDate: Date) {
  if (isDesktopRuntime() && toDateString(selectedDate) === toDateString(new Date())) {
    await appDataRepository.lifecycle.prepareCurrentDayState(toDateString(selectedDate))
    return
  }

  if (isDesktopRuntime()) {
    await appDataRepository.lifecycle.prepareCurrentDayState(toDateString(selectedDate))
    return
  } else {
    await ensureDailyLogbookUpToDate()
  }

  await syncSelectedDateData(selectedDate)
}

function buildVisibleTodoViewModels(appData: Awaited<ReturnType<typeof appDataRepository.get>>, selectedDateKey: string) {
  const dayPlanItems = sortTodoItems(
    appData.dayPlanItems.filter(
      (item) => item.status !== 'deleted' && isVisibleOnSelectedDate(item, selectedDateKey),
    ),
  )

  return mapDayPlanItemsToTodoViewModels(dayPlanItems, {
    recurringInstancesById: buildRecurringInstancesById(appData.recurringTaskInstances),
    templateKindsById: buildTemplateKindMap(appData.taskTemplates),
    templatesById: buildTemplatesById(appData.taskTemplates),
  })
}


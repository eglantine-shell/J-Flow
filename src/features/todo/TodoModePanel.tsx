function canReturnGrassTodoToList(viewModel: TodoViewModel) {
  const { template } = viewModel.internalRef

  return (
    !viewModel.isCompleted &&
    viewModel.canDelete &&
    isGrassTodo(viewModel) &&
    template?.grassStatus === 'picked'
  )
}


    const intervalValue = parseRepeatIntervalValue(repeatIntervalValueDraft)

    if (!intervalValue) {
      return null
    }

    return {
      repeatType: repeatTypeDraft,
      intervalUnit: repeatIntervalUnitDraft,
      intervalValue,
    }
